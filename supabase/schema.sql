-- Attendance IQ schema. Run in Supabase SQL Editor as project owner.
create extension if not exists pgcrypto;
create table if not exists public.user_roles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 role text not null check (role in ('admin','hr','member')),
 created_at timestamptz not null default now()
);
-- Preserve source fields as text, including blank and '-' values.
create table if not exists public.employee_master (
 id uuid primary key default gen_random_uuid(),
 sr_no bigint generated by default as identity,
 taging text, ecn_id text not null unique, name text not null, mobile text,
 allocation text, department text, sub_dep text, designation text, agency text,
 weekly_off text, active text, gender text, location text, travel_source text,
 shift_time text, shift text, birth_date text, aging text, today text, doj text,
 doj_as_per_mars text, dol text, reason_for_leaving text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.daily_attendance (
 id uuid primary key default gen_random_uuid(),
 attendance_date date not null,
 ecn_id text not null references public.employee_master(ecn_id) on update cascade on delete restrict,
 biometric_code text, manual_code text, shift_code text,
 weekly_off boolean not null default false, source_file text, notes text,
 created_by uuid references auth.users(id), created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(), unique(attendance_date,ecn_id)
);
create or replace function public.current_app_role() returns text language sql stable security definer set search_path=public
as $$ select role from public.user_roles where user_id=auth.uid() $$;
create or replace function public.is_staff() returns boolean language sql stable security definer set search_path=public
as $$ select coalesce(public.current_app_role() in ('admin','hr','member'),false) $$;
create or replace function public.can_manage() returns boolean language sql stable security definer set search_path=public
as $$ select coalesce(public.current_app_role() in ('admin','hr'),false) $$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public
as $$ select coalesce(public.current_app_role()='admin',false) $$;
alter table public.user_roles enable row level security;
alter table public.employee_master enable row level security;
alter table public.daily_attendance enable row level security;
drop policy if exists "Users can read own role" on public.user_roles;
create policy "Users can read own role" on public.user_roles for select to authenticated using (user_id=auth.uid() or public.is_admin());
drop policy if exists "Admins manage roles" on public.user_roles;
create policy "Admins manage roles" on public.user_roles for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Authorized team read employees" on public.employee_master;
create policy "Authorized team read employees" on public.employee_master for select to authenticated using (public.is_staff());
drop policy if exists "HR admin insert employees" on public.employee_master;
create policy "HR admin insert employees" on public.employee_master for insert to authenticated with check (public.can_manage());
drop policy if exists "HR admin update employees" on public.employee_master;
create policy "HR admin update employees" on public.employee_master for update to authenticated using (public.can_manage()) with check (public.can_manage());
drop policy if exists "Admin delete employees" on public.employee_master;
create policy "Admin delete employees" on public.employee_master for delete to authenticated using (public.is_admin());
drop policy if exists "Authorized team read attendance" on public.daily_attendance;
create policy "Authorized team read attendance" on public.daily_attendance for select to authenticated using (public.is_staff());
drop policy if exists "HR admin insert attendance" on public.daily_attendance;
create policy "HR admin insert attendance" on public.daily_attendance for insert to authenticated with check (public.can_manage());
drop policy if exists "HR admin update attendance" on public.daily_attendance;
create policy "HR admin update attendance" on public.daily_attendance for update to authenticated using (public.can_manage()) with check (public.can_manage());
drop policy if exists "Admin delete attendance" on public.daily_attendance;
create policy "Admin delete attendance" on public.daily_attendance for delete to authenticated using (public.is_admin());
create or replace function public.touch_updated_at() returns trigger language plpgsql as $$ begin new.updated_at=now(); return new; end $$;
drop trigger if exists employee_master_touch_updated_at on public.employee_master;
create trigger employee_master_touch_updated_at before update on public.employee_master for each row execute function public.touch_updated_at();
drop trigger if exists daily_attendance_touch_updated_at on public.daily_attendance;
create trigger daily_attendance_touch_updated_at before update on public.daily_attendance for each row execute function public.touch_updated_at();
create index if not exists employee_master_department_idx on public.employee_master(department);
create index if not exists employee_master_agency_idx on public.employee_master(agency);
create index if not exists employee_master_designation_idx on public.employee_master(designation);
create index if not exists attendance_date_idx on public.daily_attendance(attendance_date);
create index if not exists attendance_shift_idx on public.daily_attendance(shift_code);
